#!/usr/bin/env bash
# Build a uvl app as an Android APK (NativeActivity, no Java code).
#
#   android/build.sh [Module] [init-symbol]
#
# Defaults to the phone example (`Examples.PhoneAndroid`, which exports
# `uvl_android_make`). Requires:
#   - the Android NDK (r26 or newer): ANDROID_NDK_HOME or ANDROID_NDK_ROOT,
#   - the Android SDK with build-tools and a platform: ANDROID_HOME
#     (or ANDROID_SDK_ROOT),
#   - a JDK (keytool and apksigner run on Java), cmake and git,
#   - the Lean toolchain from lean-toolchain.
#
# Like web/build.sh, it builds what Lean only ships as host code, once per ABI,
# and caches it under .lake/build/android:
#   1. the Lean runtime (C++) from the sources of the exact toolchain version,
#      with libuv built for Android,
#   2. `Init` (C generated by `lean -c` from the toolchain's own sources),
# then compiles the app's Lake-generated C and android/android_shell.c into
# lib/<abi>/libuvl.so and packages, aligns and signs the APK.
#
# Environment:
#   ANDROID_ABIS     ABIs to build (default "arm64-v8a"; also x86_64, armeabi-v7a, x86)
#   UVL_APK          output path (default android/dist/uvl-example.apk)
#   UVL_KEYSTORE     keystore to sign with (default: a generated debug key in the cache);
#                    UVL_KEYSTORE_PASS and UVL_KEY_ALIAS go with it
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MODULE=${1:-Examples.PhoneAndroid}
INIT_SYM=${2:-initialize_uvl_$(echo "$MODULE" | tr . _)}
JOBS=${JOBS:-$(nproc 2>/dev/null || echo 4)}
ABIS=${ANDROID_ABIS:-arm64-v8a}
API=28
CORE_EXTRA=${CORE_EXTRA:-Std.Tactic.BVDecide.Bitblast.BoolExpr.Basic Std.Tactic.BVDecide.Bitblast.BVExpr.Basic}
LIBUV_VERSION=v1.48.0

NDK=${ANDROID_NDK_HOME:-${ANDROID_NDK_ROOT:-}}
SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}
[ -n "$NDK" ] && [ -d "$NDK" ] || { echo "error: set ANDROID_NDK_HOME to an Android NDK" >&2; exit 1; }
[ -n "$SDK" ] && [ -d "$SDK" ] || { echo "error: set ANDROID_HOME to an Android SDK" >&2; exit 1; }
HOST_TAG=$(ls "$NDK/toolchains/llvm/prebuilt" | head -1)
LLVM=$NDK/toolchains/llvm/prebuilt/$HOST_TAG/bin
BUILD_TOOLS=$(ls -d "$SDK"/build-tools/* | grep -E '/[0-9.]+$' | sort -V | tail -1)
PLATFORM=$(ls -d "$SDK"/platforms/android-* | grep -E '/android-[0-9]+$' | sort -V | tail -1)

PREFIX=$(lean --print-prefix)
VERSION=$(lean --version | sed -E 's/.*version ([0-9][^ ,]*).*/\1/')
CACHE=$ROOT/.lake/build/android/v$VERSION
APK=${UVL_APK:-$ROOT/android/dist/uvl-example.apk}
mkdir -p "$CACHE" "$(dirname "$APK")"
cd "$ROOT"

log() { echo "==> $*"; }

triple() {
  case "$1" in
    arm64-v8a) echo aarch64-linux-android ;;
    armeabi-v7a) echo armv7a-linux-androideabi ;;
    x86_64) echo x86_64-linux-android ;;
    x86) echo i686-linux-android ;;
    *) echo "error: unknown ABI $1" >&2; exit 1 ;;
  esac
}

# --- sources shared by every ABI ---------------------------------------------
INC=$CACHE/include
if [ ! -f "$INC/lean/config.h" ]; then
  mkdir -p "$INC/lean"
  cp "$PREFIX/include/lean/lean.h" "$PREFIX/include/lean/version.h" "$INC/lean/"
  printf '#pragma once\n#include <lean/version.h>\n#define LEAN_IS_STAGE0 0\n' > "$INC/lean/config.h"
  printf '#define LEAN_GITHASH ""\n' > "$INC/githash.h"
fi
SRC=$CACHE/lean4
if [ ! -d "$SRC/src/runtime" ]; then
  log "fetching Lean v$VERSION runtime sources"
  git clone -q --depth 1 --filter=blob:none --sparse --branch "v$VERSION" \
    https://github.com/leanprover/lean4.git "$SRC"
  git -C "$SRC" sparse-checkout set src/runtime src/include src/util
fi
UV=$CACHE/libuv
if [ ! -f "$UV/CMakeLists.txt" ]; then
  git clone -q --depth 1 --branch "$LIBUV_VERSION" https://github.com/libuv/libuv.git "$UV"
fi

# Init and the extra core modules as C (target independent)
INIT_C=$CACHE/init-c
if [ ! -f "$INIT_C/.done" ]; then
  log "generating C for Init (takes a few minutes, cached)"
  mkdir -p "$INIT_C"
  (cd "$PREFIX/src/lean" && { echo Init.lean; find Init -name '*.lean'; }) |
    xargs -P "$JOBS" -I{} sh -c 'f={}; cd '"$PREFIX/src/lean"' &&
      lean --root=. -c '"$INIT_C"'/$(echo "${f%.lean}" | tr / _).c "$f" > /dev/null'
  touch "$INIT_C/.done"
fi
EXTRA_KEY=$(echo "$CORE_EXTRA" | md5sum | cut -c1-12)
EXTRA_C=$CACHE/extra-c-$EXTRA_KEY
if [ ! -f "$EXTRA_C/.done" ]; then
  mkdir -p "$EXTRA_C"
  for m in $CORE_EXTRA; do
    (cd "$PREFIX/src/lean" && lean --root=. -c "$EXTRA_C/$(echo "$m" | tr . _).c" "$(echo "$m" | tr . /).lean" > /dev/null)
  done
  touch "$EXTRA_C/.done"
fi

# the app's C: the import closure of the module within this package
log "building $MODULE"
lake build "$MODULE:c" > /dev/null
APP_LIST=$CACHE/app-list
python3 - "$MODULE" > "$APP_LIST" <<'PY'
import os, sys
seen, todo = set(), [sys.argv[1]]
while todo:
    m = todo.pop()
    path = m.replace('.', '/') + '.lean'
    if m in seen or not os.path.exists(path):
        continue  # outside the package (Init, Lean, Std)
    seen.add(m)
    for line in open(path, encoding='utf-8'):
        if line.startswith('import '):
            todo += line.split()[1:]
for m in sorted(seen):
    print('.lake/build/ir/' + m.replace('.', '/') + '.c')
PY

STAGE=$CACHE/apk
rm -rf "$STAGE" && mkdir -p "$STAGE/lib"

for ABI in $ABIS; do
  TRIPLE=$(triple "$ABI")
  CC="$LLVM/clang --target=$TRIPLE$API"
  CXX="$LLVM/clang++ --target=$TRIPLE$API"
  CFLAGS="-O2 -DNDEBUG -fPIC -ffunction-sections -fdata-sections -w"
  OUT=$CACHE/$ABI
  mkdir -p "$OUT"

  # --- 1. libuv and the runtime ----------------------------------------------
  if [ ! -f "$OUT/libuv.a" ]; then
    log "[$ABI] building libuv"
    cmake -S "$UV" -B "$OUT/libuv-build" -G "Unix Makefiles" \
      -DCMAKE_TOOLCHAIN_FILE="$NDK/build/cmake/android.toolchain.cmake" \
      -DANDROID_ABI="$ABI" -DANDROID_PLATFORM="android-$API" -DCMAKE_BUILD_TYPE=Release \
      -DLIBUV_BUILD_TESTS=OFF -DLIBUV_BUILD_BENCH=OFF -DLIBUV_BUILD_SHARED=OFF > /dev/null
    cmake --build "$OUT/libuv-build" --parallel "$JOBS" > /dev/null
    cp "$OUT/libuv-build/libuv.a" "$OUT/libuv.a"
  fi
  if [ ! -f "$OUT/libleanrt.a" ]; then
    log "[$ABI] compiling the Lean runtime"
    OBJ=$OUT/rt-obj
    rm -rf "$OBJ" && mkdir -p "$OBJ"
    RT="debug thread mpz utf8 object apply exception interrupt memory stackinfo compact
        init_module io hash byteslice platform alloc allocprof sharecommon stack_overflow
        process object_ref mpn mutex libuv uv/net_addr uv/event_loop uv/timer uv/tcp uv/udp
        uv/dns uv/signal uv/system"
    for f in $RT; do echo "$SRC/src/runtime/$f.cpp"; done > "$OBJ/list"
    xargs -P "$JOBS" -I{} sh -c 'f={}; o='"$OBJ"'/$(echo "$f" | md5sum | cut -c1-12).o;
      '"$CXX"' -std=c++20 -DLEAN_MULTI_THREAD '"$CFLAGS"' -I'"$INC"' -I'"$SRC/src"' \
        -I'"$SRC/src/runtime"' -I'"$UV/include"' -c "$f" -o "$o"' < "$OBJ/list"
    # no OpenSSL on Android: its no-OpenSSL variant only reports a version of 0
    $CXX -std=c++20 $CFLAGS -DLEAN_EMSCRIPTEN -I"$INC" -I"$SRC/src" -c "$SRC/src/runtime/openssl.cpp" -o "$OBJ/openssl.o"
    "$LLVM/llvm-ar" rcs "$OUT/libleanrt.a" "$OBJ"/*.o
  fi

  # --- 2. Init and the extra core modules --------------------------------------
  if [ ! -f "$OUT/libInit.a" ]; then
    log "[$ABI] compiling Init"
    OBJ=$OUT/init-obj
    rm -rf "$OBJ" && mkdir -p "$OBJ"
    ls "$INIT_C"/*.c | xargs -P "$JOBS" -I{} sh -c 'f={}; '"$CC"' '"$CFLAGS"' -I'"$INC"' -c "$f" -o '"$OBJ"'/$(basename "${f%.c}").o'
    "$LLVM/llvm-ar" rcs "$OUT/libInit.a" "$OBJ"/*.o
  fi
  if [ ! -f "$OUT/libExtra-$EXTRA_KEY.a" ]; then
    OBJ=$OUT/extra-obj-$EXTRA_KEY
    rm -rf "$OBJ" && mkdir -p "$OBJ"
    for f in "$EXTRA_C"/*.c; do $CC $CFLAGS -I"$INC" -c "$f" -o "$OBJ/$(basename "${f%.c}").o"; done
    "$LLVM/llvm-ar" rcs "$OUT/libExtra-$EXTRA_KEY.a" "$OBJ"/*.o
  fi

  # --- 3. the app ---------------------------------------------------------------
  log "[$ABI] compiling the app"
  APP=$OUT/app
  rm -rf "$APP" && mkdir -p "$APP"
  xargs -P "$JOBS" -I{} sh -c 'f={}; o='"$APP"'/$(echo "$f" | sed "s|.lake/build/ir/||; s|/|_|g").o;
    '"$CC"' '"$CFLAGS"' -I'"$INC"' -c "$f" -o "$o"' < "$APP_LIST"
  GLUE=$NDK/sources/android/native_app_glue
  $CC $CFLAGS -I"$INC" -I"$GLUE" -DUVL_ANDROID_INIT="$INIT_SYM" -c android/android_shell.c -o "$APP/android_shell.o"
  $CC $CFLAGS -I"$GLUE" -c "$GLUE/android_native_app_glue.c" -o "$APP/android_native_app_glue.o"
  $CC $CFLAGS -I"$INC" -c android/lean_stubs.c -o "$APP/lean_stubs.o"

  # --- 4. link, with stubs for compile-time-only symbols -------------------------
  # Elaborators and `bv_decide` reflection terms reference `Lean`/`Std`, which
  # are not linked. Closed terms are initialized lazily, so this code never runs
  # in an app; the stubs panic loudly if it ever does (see web/build.sh).
  SO=$STAGE/lib/$ABI/libuvl.so
  mkdir -p "$(dirname "$SO")"
  LINK=($CXX -shared -o "$SO" "$APP"/*.o "$OUT/libExtra-$EXTRA_KEY.a" "$OUT/libInit.a" "$OUT/libleanrt.a"
        "$OUT/libuv.a" -landroid -llog -lm -static-libstdc++ -u ANativeActivity_onCreate
        -Wl,--no-undefined -Wl,--gc-sections -Wl,-z,max-page-size=16384 -Wl,--error-limit=0)
  if ! "${LINK[@]}" 2> "$APP/link1.log"; then
    grep -o 'undefined symbol: [A-Za-z0-9_]*' "$APP/link1.log" | cut -d' ' -f3 | sort -u > "$APP/undef" || true
    if [ ! -s "$APP/undef" ]; then cat "$APP/link1.log" >&2; exit 1; fi
    # also specializations made in Lean/Std of core functions (`l_List_lookup___at___00Lean_...`)
    BAD=$(grep -v -E '^(l_.*(Lean|Std)_|initialize_Lean|initialize_Std)' "$APP/undef" || true)
    if [ -n "$BAD" ]; then
      echo "error: undefined symbols that are not compile-time-only:" >&2
      echo "$BAD" >&2
      exit 1
    fi
    STUBS=$APP/gen_stubs.c
    { echo '#include <lean/lean.h>'
      for m in $CORE_EXTRA; do echo "lean_object *initialize_$(echo "$m" | tr . _)(uint8_t);"; done
      echo 'static lean_object *init_extra(uint8_t b) {'
      for m in $CORE_EXTRA; do
        echo "  { lean_object *r = initialize_$(echo "$m" | tr . _)(b); if (lean_io_result_is_error(r)) return r; lean_dec_ref(r); }"
      done
      echo '  return lean_io_result_mk_ok(lean_box(0));'
      echo '}'
      { grep '^initialize_' "$APP/undef" || true; } | sed 's/.*/lean_object *&(uint8_t b) { return init_extra(b); }/'
      { grep '^l_' "$APP/undef" || true; } | sed 's/.*/void &(void) { lean_internal_panic("compile-time-only symbol called: &"); }/'
    } > "$STUBS"
    log "[$ABI] stubbed $(wc -l < "$APP/undef") compile-time-only symbols"
    $CC $CFLAGS -I"$INC" -c "$STUBS" -o "$APP/gen_stubs.o"
    "${LINK[@]}" "$APP/gen_stubs.o" 2> "$APP/link2.log" || { cat "$APP/link2.log" >&2; exit 1; }
  fi
  "$LLVM/llvm-strip" --strip-unneeded "$SO"
  log "[$ABI] $(du -h "$SO" | cut -f1) libuvl.so"
done

# --- 5. package, align and sign ------------------------------------------------
log "packaging with $(basename "$BUILD_TOOLS") and $(basename "$PLATFORM")"
"$BUILD_TOOLS/aapt2" link -o "$STAGE/base.apk" --manifest android/AndroidManifest.xml \
  -I "$PLATFORM/android.jar" --min-sdk-version "$API" --target-sdk-version 34
# native libraries are stored uncompressed and page-aligned so they load in place
(cd "$STAGE" && zip -q -0 -r base.apk lib)
if "$BUILD_TOOLS/zipalign" 2>&1 | grep -q -- ' -P '; then
  "$BUILD_TOOLS/zipalign" -f -P 16 4 "$STAGE/base.apk" "$STAGE/aligned.apk"
else
  "$BUILD_TOOLS/zipalign" -f -p 4 "$STAGE/base.apk" "$STAGE/aligned.apk"
fi
KEYSTORE=${UVL_KEYSTORE:-$ROOT/.lake/build/android/debug.keystore}
PASS=${UVL_KEYSTORE_PASS:-android}
ALIAS=${UVL_KEY_ALIAS:-androiddebugkey}
if [ ! -f "$KEYSTORE" ]; then
  keytool -genkeypair -keystore "$KEYSTORE" -storepass "$PASS" -keypass "$PASS" -alias "$ALIAS" \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=UVL Debug,O=UVL,C=US" > /dev/null 2>&1
fi
"$BUILD_TOOLS/apksigner" sign --ks "$KEYSTORE" --ks-pass "pass:$PASS" --ks-key-alias "$ALIAS" \
  --out "$APK" "$STAGE/aligned.apk"
log "done: $APK ($(du -h "$APK" | cut -f1), $ABIS)"
