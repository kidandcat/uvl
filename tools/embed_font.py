#!/usr/bin/env python3
"""Embed a font file into a Lean module as a base64 string literal.

    tools/embed_font.py assets/fonts/UVLSans-Regular.ttf UVL/Text/UVLSansData.lean uvlSansBase64

The generated module has no imports, so it compiles everywhere (including the
WebAssembly and bare-metal builds) without pulling in the Lean compiler.
"""
import base64, sys

src, dst, name = sys.argv[1:4]
data = base64.b64encode(open(src, "rb").read()).decode()
lines = [data[i:i + 96] for i in range(0, len(data), 96)]
body = '  "' + "\\\n    ".join(lines) + '"'
open(dst, "w").write(f"""/-!
# Embedded font data

Generated by `tools/embed_font.py` from `{src}` (see `assets/fonts/OFL.txt` for
its license). Do not edit by hand.
-/

namespace UVL.Text

/-- `{src.split('/')[-1]}`, base64-encoded. -/
def {name} : String :=
{body}

end UVL.Text
""")
